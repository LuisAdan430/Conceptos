/*
    * La inyección de dependencias (DI - Dependency Injection) es un patrón de diseño que se utiliza en la
    * programación orientada a objetos para gestionar las dependencias entre clases, promoviendo un
    * código más modular, reutilizable y fácil de mantener. La DI permite que los objetos reciban sus     
    * dependencias desde un contenedor externo en lugar de crearlas ellos mismos, lo que mejora la
    * separación de responsabilidades y facilita las pruebas unitarias.
*/

